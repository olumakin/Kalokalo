"""
Export every logged forecast for the current season, all leagues, read
directly from Supabase. Read-only -- SELECT queries only, never writes
to predictions/settlements/gate_status and never touches app or model
code.

    python -m scripts.export_full_forecast_history \
        [--since 2026-08-01] [--until 2026-10-26] \
        [--out kalokalo_forecasts_2026_27.csv] \
        [--backtest-out kalokalo_forecasts_2026_27_backtest_reruns.csv]

Two output files:

- `--out`: one row per fixture, using the last forecast saved strictly
  before kick-off (created_at < match_date) -- the real, served,
  pre-match forecast. A fixture with no such row (every logged
  prediction for it was created on or after its match_date -- i.e.
  the model was only ever re-run against it after the fact) has no
  row here.
- `--backtest-out`: every row where created_at >= match_date -- a
  forecast generated by re-running the model on a match that had
  already been played, not a real pre-kickoff call. Not deduped
  (a fixture can have several such reruns); each one is kept.

Both files share the same columns. `source_type` records which bucket
a row came from ("live" or "backtest") so the split is traceable even
if the two CSVs are later recombined.

Unlike every other fetch_* in src.tracking.supabase_ledger, this
queries Supabase directly with real range()-based pagination -- no
client-side row cap, however many predictions/settlements exist this
season.
"""
from __future__ import annotations

import argparse

import pandas as pd

from src.ingestion.historical import current_season_start
from src.ingestion.normalizer import load_team_mappings, resolve_display_name
from src.tracking.supabase_ledger import get_supabase_client

# Must match app.py's HIGH_TIE_P_DRAW and the is_high_tie check that
# drives the "HIGH DRAW LIKELIHOOD" / "HIGH TIE POTENTIAL" badge
# (app.py: `is_high_tie = match["p_draw"] >= HIGH_TIE_P_DRAW`).
HIGH_TIE_P_DRAW = 0.275
FLAG_RULE = f"p_draw >= {HIGH_TIE_P_DRAW}"

PAGE_SIZE = 1000

OUTPUT_COLUMNS = [
    "fixture_id", "league", "match_date_utc", "home_team_full_name", "away_team_full_name", "home_id", "away_id",
    "forecast_created_at_utc", "model_version", "git_commit", "converged", "fallback_used",
    "p_home", "p_draw", "p_away", "high_draw_flag", "flag_rule",
    "entry_home_odds", "entry_draw_odds", "entry_away_odds", "entry_source",
    "market_p_home", "market_p_draw", "market_p_away",
    "close_draw_odds", "home_goals", "away_goals", "actual_result", "source_type",
]


def _paged_select(client, table: str, columns: str = "*", filters: list[tuple] | None = None) -> pd.DataFrame:
    """Every row of `table` matching `filters` (a list of (method, *args)
    calls applied to the query builder, e.g. [("gte", "match_date",
    "2026-08-01")]), paged with .range() so PostgREST's default
    row cap never silently truncates the result."""
    rows: list[dict] = []
    offset = 0
    while True:
        query = client.table(table).select(columns)
        for method, *args in filters or []:
            query = getattr(query, method)(*args)
        query = query.order("fixture_id")
        query = query.order("created_at" if table == "predictions" else "settled_at")
        resp = query.range(offset, offset + PAGE_SIZE - 1).execute()
        batch = resp.data or []
        rows.extend(batch)
        if len(batch) < PAGE_SIZE:
            break
        offset += PAGE_SIZE
    return pd.DataFrame(rows)


def fetch_all_predictions(client, since: pd.Timestamp, until: pd.Timestamp) -> pd.DataFrame:
    return _paged_select(
        client, "predictions",
        filters=[("gte", "match_date", since.isoformat()), ("lte", "match_date", until.isoformat())],
    )


def fetch_all_settlements(client) -> pd.DataFrame:
    return _paged_select(client, "settlements")


def latest_settlement_per_fixture(settlements: pd.DataFrame) -> pd.DataFrame:
    if settlements.empty:
        return settlements
    df = settlements.copy()
    df["settled_at"] = pd.to_datetime(df["settled_at"])
    return df.sort_values("settled_at").drop_duplicates(subset="fixture_id", keep="last")


def build_rows(predictions: pd.DataFrame, settlements: pd.DataFrame, mappings: dict) -> pd.DataFrame:
    if predictions.empty:
        return pd.DataFrame(columns=OUTPUT_COLUMNS)

    df = predictions.copy()
    df["match_date"] = pd.to_datetime(df["match_date"], utc=True)
    df["created_at"] = pd.to_datetime(df["created_at"], utc=True)
    df["source_type"] = df["created_at"].lt(df["match_date"]).map({True: "live", False: "backtest"})

    df["high_draw_flag"] = df["p_draw"] >= HIGH_TIE_P_DRAW
    df["flag_rule"] = FLAG_RULE
    df["home_team_full_name"] = df.apply(lambda r: resolve_display_name(r["home_id"], r["league"], mappings), axis=1)
    df["away_team_full_name"] = df.apply(lambda r: resolve_display_name(r["away_id"], r["league"], mappings), axis=1)
    df["match_date_utc"] = df["match_date"]
    df["forecast_created_at_utc"] = df["created_at"]

    df = df.rename(columns={
        "entry_home": "entry_home_odds", "entry_draw": "entry_draw_odds", "entry_away": "entry_away_odds",
        "close_draw": "close_draw_odds",
    })

    if not settlements.empty:
        settled = latest_settlement_per_fixture(settlements)[["fixture_id", "home_goals", "away_goals", "actual_result"]]
        df = df.merge(settled, on="fixture_id", how="left")
    else:
        df["home_goals"] = pd.NA
        df["away_goals"] = pd.NA
        df["actual_result"] = pd.NA

    for col in OUTPUT_COLUMNS:
        if col not in df.columns:
            df[col] = pd.NA

    return df[OUTPUT_COLUMNS]


def main() -> None:
    parser = argparse.ArgumentParser(description="Export every logged forecast this season, direct from Supabase")
    parser.add_argument("--since", default=None, help="YYYY-MM-DD; defaults to this season's start (Aug 1)")
    parser.add_argument("--until", default=None, help="YYYY-MM-DD; defaults to today")
    parser.add_argument("--out", default="kalokalo_forecasts_2026_27.csv")
    parser.add_argument("--backtest-out", default="kalokalo_forecasts_2026_27_backtest_reruns.csv")
    args = parser.parse_args()

    since = pd.Timestamp(args.since, tz="UTC") if args.since else current_season_start()
    until = pd.Timestamp(args.until, tz="UTC") if args.until else pd.Timestamp.now(tz="UTC")

    client = get_supabase_client()
    if client is None:
        raise SystemExit("Supabase credentials not configured (SUPABASE_URL / SUPABASE_ANON_KEY).")

    predictions = fetch_all_predictions(client, since, until)
    settlements = fetch_all_settlements(client)
    mappings = load_team_mappings()

    rows = build_rows(predictions, settlements, mappings)

    live = rows[rows["source_type"] == "live"].copy()
    live = live.sort_values("forecast_created_at_utc").drop_duplicates(subset="fixture_id", keep="last")
    live = live.sort_values("match_date_utc").reset_index(drop=True)

    backtest = rows[rows["source_type"] == "backtest"].sort_values("match_date_utc").reset_index(drop=True)

    live.to_csv(args.out, index=False)
    backtest.to_csv(args.backtest_out, index=False)

    print(f"Wrote {len(live)} live (pre-kickoff) fixture row(s), since {since.date()} to {until.date()}, to {args.out}")
    print(f"Wrote {len(backtest)} backtest-rerun row(s) to {args.backtest_out}")


if __name__ == "__main__":
    main()
